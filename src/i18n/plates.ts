/** "znak", "znaki" or "znaków" for a count (Polish plural). */
function characters(count: number) {
  if (count === 1) return 'znak';
  const tens = count % 100;
  const units = count % 10;
  return units >= 2 && units <= 4 && (tens < 12 || tens > 14) ? 'znaki' : 'znaków';
}
